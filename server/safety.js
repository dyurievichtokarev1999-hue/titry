const HARM_PERSON = new RegExp(String.raw`(?<![а-я])причинить\s+${PERSON}\s+(?:вред|боль)|(?<![а-я])слома\S*\s+${PERSON}\s+(?:руки|руку|ноги|ногу|шею|нос|челюсть)|(?<![а-я])(?:расправ\S*|разберусь|поквитаюсь|сведу\s+счеты)\s+со?\s+${PERSON}(?![а-я])|(?<![а-я])${HARM_VERB}(?![а-я])(?:\s+(?!(?:с|со|вместе)\s)\S+){0,2}?\s+(?:на\s+)?(?<!(?:с|со)\s)${PERSON}(?![а-я])|(?<![а-я])${PERSON}(?![а-я])(?:[^а-я\s]{1,8}[а-я]{0,20}){0,3}(?:\s+\S+){0,6}?\s+${HARM_VERB}(?![а-я])|(?<![а-я])разобь\S*\s+${PERSON}\s+(?:голову|лицо|морду|нос|башку)|(?<![а-я])(?:положу|подсыплю|подмешаю|насыплю|подолью)\s+${PERSON}\s+(?:\S+\s+)?(?:яд\S*|отрав\S*)|(?<![а-я])(?:положу|подсыплю|подмешаю|насыплю|подолью)\s+(?:\S+\s+)?(?:яд\S*|отрав\S*)\s+${PERSON}(?![а-я])`);
// Ложное совпадение «глагол + своё дополнение, запятая, другой человек» («побил свой рекорд, тренер…»,
// «убил весь вечер, мама…»): после глагола сразу неличное дополнение и конец части. Вводные слова между объектом
// и глаголом («Соседа, честно, завтра убью») этим не отсекаются — совпадение начинается с человека.
const NOMINATIVE = /^(?:тренер|брат|сестра|мама|мать|папа|отец|муж|жена|сосед|соседка|коллега|начальник|начальница|друг|подруга|сын|дочь|учитель|учительница|бабушка|дедушка|ребенок|он|она|они|мы|все|кто|парень|девушка|шеф|директор)$/;
const VERB_FIRST = new RegExp(String.raw`^(?:причинить|слома|разобь|расправ|разберусь|поквитаюсь|сведу|положу|подсыплю|подмешаю|насыплю|подолью|${HARM_VERB})`);
// Разбор ed3ed760: дополнение в угрозе часто опущено («Шеф наорал, завтра пристрелю»). Человек в именительном
// отбрасывается, только если сразу за глаголом — неличное дополнение («прибью полку», «ударю по газам»,
// «побью свой рекорд»). Конец части, наречие, маркер времени, человек, творительный (средство) — угроза остаётся.
const BODY = /^(?:бок|голов|лиц|морд|башк|рук|ног|шее|шею|горл|спин|живот|глаз|зуб|нос|челюст|ребр)/;
// Неличное дополнение — только из короткого списка предметов (или «по/на» + не часть тела и не человек).
// Неизвестное слово после глагола угрозу не снимает (разбор 18588362): пропуск хуже лишней остановки.
const THING = /^(?:полку|полочку|полки|доску|доски|картину|картины|гвоздь|гвозди|рекорд|время|день|вечер|час|черновик|черновики|танцпол|шкаф|ковер|ковры|вешалку|тест|экзамен|таракана|тараканов|муху|мух|комара|комаров|муравьев|сорняки|свой|свою|свое|свои|мой|мою|мое|мои|весь|всю|баннер|плакат|карниз|зеркало|часы|ящик|замок|дверь|сетку|бумагу|бумаги|тетрадь|тетради|старые|старый|старую|старое|принтер|компьютер|ноутбук|грушу|мяч|зомби|босса)$/;
// Безобидные продолжения с «по/на» — только из перечня («ударю по газам», «двину на дачу»); «убью на перемене» — угроза.
const PO_NA_THING = /^(?:газам|газу|рукам|клавишам|клавиатуре|мячу|столу|стене|шайбе|воротам|тормозам|кнопке|кнопкам|струнам|барабанам|дачу|работу|природу|рыбалку|концерт|море|педали|педаль|танцпол|учебе|учебу)$/;
const PERSON_WORD_RE = new RegExp(String.raw`^${PERSON}$`);
function thingObjectAfter(s, pos) {
  const tail = s.slice(pos, pos + 80);
  if (/^\s*(?:[.!?…;:,—–-]|$)/.test(tail)) return false; // конец части — дополнение опущено
  const [a = '', b = ''] = tail.trim().split(/[^а-я]+/).filter(Boolean);
  if (!a || PERSON_WORD_RE.test(a)) return false;
  if (/^(?:по|на)$/.test(a)) return PO_NA_THING.test(b);
  return THING.test(a); // целая форма винительного; творительный («полкой», «доской») — средство, угроза остаётся
}
const NOMINATIVE_SUBJ = /^(?:тренер|брат|сестра|мама|папа|отец|муж|жена|сосед|соседка|соседи|коллега|коллеги|начальник|начальница|друг|друзья|подруга|подруги|сын|учитель|учительница|бабушка|дедушка|ребенок|дети|родители|братья|сестры|люди|парень|девушка|шеф|директор|отчим|мачеха|тренеры|дядя|тетя)$/;
// «Отчим вчера избил.» — насилие без дополнения (чаще всего над рассказчиком): не none, а concern; для титров — опасная часть.
const PAST_NO_OBJ_RE = new RegExp(String.raw`(?<![а-я])(?:${NOMINATIVE_SUBJ.source.slice(4, -2)}|он|она|они|мать|дочь)(?:\s+[а-я]+){0,4}?\s+(?:из?бил[аи]?|побил[аи]?|ударил[аи]?|душил[аи]?|придушил[аи]?|бил[аи]?|толкнул[аи]?|пнул[аи]?|порезал[аи]?|отлупил[аи]?|выпорол[аи]?|врезал[аи]?|отметелил[аи]?|избивал[аи]?)(?:\s+(?:до\s+крови|ремнем|ремнём|сильно|больно|жестоко|ногой|ногами|кулаком|кулаками|опять|снова))?(?=\s*(?:[.!?…;,—–:()]|$))`);
// 12-й разбор 8afb30ae: «безобидный контекст» (игра, спорт) за три раунда так и не перестал прятать насилие
// («шайбой по лицу», «словно мяч пинал», «мяч. Мне больно.») — убран. «Брат ударил, и мяч влетел» — лишняя
// остановка (concern), это допустимо.
const PAST_NO_OBJ = { test: (x) => PAST_NO_OBJ_RE.test(x) };
const OWN_OBJECT = new RegExp(String.raw`^${HARM_VERB}\s+(?:свой|свою|свое|свои|своих|весь|всю|все|целый|целую|целое|время|рекорд|день|вечер|вечеринку|выходные|настроение|интерес)(?:\s+([а-я]+))?[,;:—–]`);
export function harmPerson(s) {
  const re = new RegExp(HARM_PERSON.source, 'g');
  let m;
  while ((m = re.exec(s))) {
    // Своё дополнение — не человек («свою жену, решено» — угроза). Отброшенное совпадение не скрывает следующее:
    // поиск продолжается со следующего знака, а не после всего совпадения («убью весь день, соседа убью тоже»).
    // Обратная форма «ЧЕЛОВЕК … ГЛАГОЛ»: человек в именительном — подлежащее («Соседи шумят, завтра прибью полку»),
    // не объект. «Мать», «дочь» совпадают с винительным и не исключаются.
    if (!VERB_FIRST.test(m[0]) && NOMINATIVE_SUBJ.test(m[0].split(/[^а-я]+/)[0])) {
      // Подлежащее перед глаголом в прошедшем («Брат избил маму, завтра убью») — всегда отбрасывается, поиск идёт
      // дальше и находит «избил маму», «убью». Перед глаголом не в прошедшем — только при неличном дополнении.
      const verb = m[0].split(/\s+/).pop().replace(/[^а-я]+$/, ''); // «избил,» — тот же глагол
      // «бы» рядом («так бы и убил») — прошедшее время значит желание рассказчика, совпадение остаётся.
      const wouldBe = /(?<![а-я])бы(?![а-я])/.test(s.slice(Math.max(0, m.index - 12), m.index + m[0].length + 4)); // то же окно, что в harmToOthers
      if ((!wouldBe && /(?:ил|ал|ул|ел|ыл|ял)(?:а|и|о)?$/.test(verb)) || thingObjectAfter(s, m.index + m[0].length)) { re.lastIndex = m.index + 1; continue; }
    }
    const own = OWN_OBJECT.exec(m[0]);
    // Отбрасывается только «…рекорд, тренер меня обнял»: после запятой — человек в именительном (новое подлежащее).
    const after = own ? s.slice(m.index + own[0].length).trim().split(/\s+/)[0] || '' : '';
    if (!own || (own[1] && new RegExp(String.raw`^${PERSON}$`).test(own[1])) || !NOMINATIVE.test(after)) return m;
    re.lastIndex = m.index + 1;
  }
  return null;
}
const WANT = /(?:хочу|хочется|хотела|хотел|мечтаю|охота)/;
const MARKER = /(?<![а-я])(?:собираюсь|соберусь|решил\S*|решено|намерен\S*|планирую|план\S*|пойду|сегодня|завтра|ночью|вечером|сейчас|скоро|после\s+(?:работы|уроков|школы|пар)|в\s+(?:понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье)|на\s+выходных|в\s+выходные|через\s+(?:час|день|неделю))(?![а-я])/;
// Средство (оружие) рядом с намерением; «нож» — не «ножницы»; отрицание («нет ножа», «оружия у меня нет») не считается.
const WEAPON = /(?<!не\s)(?<!нет\s)(?:оружие|оружием|(?<![а-я])нож(?!ниц|ничк)\S*|пистолет\S*|ружье\S*|ружьем|бит(?:а|у|ой|о)(?![а-я]))(?![^.!?…;]{0,15}нет)/;

// Оружие и цель без глагола вреда: «Возьму нож и пойду к бывшему», «Нож в сумке. Сегодня он умрёт».
const WEAPON_PREP = /(?:возьму|взял\S*|наточил\S*|приготовил\S*|в\s+сумке|при\s+мне|за\s+поясом)/;
const DOOM = new RegExp(String.raw`(?:он|она|они)\s+(?:умрет|умрут|сдохнет|не\s+проснется)|(?<![а-я])${PERSON}\s+конец|(?:пойду|приду)\s+к\s+${PERSON}`);
function weaponPlan(sentence, whole) {
  return WEAPON.test(whole) && WEAPON_PREP.test(whole) && (DOOM.test(sentence) || DOOM.test(whole));
}
const clauses = (text) => String(text || '').split(/(?<=[.!?…;])\s+|\n+/).map((x) => x.trim()).filter(Boolean);
// Имя собственное (кириллица с заглавной, не первое слово предложения) рядом с глаголом: «убью Петю», «Серёгу урою».
const NAMED = new RegExp(String.raw`(?<![а-яА-ЯёЁ])${HARM_VERB}(?![а-я])\s+(?:\S+\s+)?[А-ЯЁ][а-яё]{2,}|[^.!?…;\s]\s+[А-ЯЁ][а-яё]{2,}\s+(?:\S+\s+)?${HARM_VERB}(?![а-я])`);
const INITIAL_NAMED = new RegExp(String.raw`^[А-ЯЁ][а-яё]{2,}[ую]\s+(?:\S+\s+){0,2}?(?!\S*(?:ил|ал|ул|ел|ыл)(?:а|и|о)?(?![а-я]))(?!\S*(?:ть|ться)(?![а-я]))${HARM_VERB}(?![а-я])`);
const namedHarm = (raw) => clauses(String(raw || '').replace(/ё/g, 'е').replace(/Ё/g, 'Е')).some((s) => NAMED.test(s.replace(/^[А-ЯЁ]/, (c) => c.toLowerCase()).replace(/^(\S+)/, (w) => w.toLowerCase())));

/** Уровень угрозы другому человеку по предложениям: 'urgent' | 'concern' | null. */
function harmToOthers(t, raw = '') {
  let level = null;
  const parts = clauses(t);
  const weapon = WEAPON.test(t);
  const rawParts = clauses(String(raw || '').replace(/ё/g, 'е').replace(/Ё/g, 'Е'));
  for (const [k, s] of parts.entries()) {
    const rp = rawParts[k];
    // Имя в начале предложения — только в винительном на -у/-ю и с личной формой глагола не в прошедшем («Серёгу урою», «Катю я сегодня придушу»; не «Пойду ударить…», не «Утку убила лиса»).
    const named = rp !== undefined && (NAMED.test(rp.replace(/^(\S+)/, (w) => w.toLowerCase())) || INITIAL_NAMED.test(rp));
    const m = harmPerson(s);
    // Человек перед глаголом в прошедшем времени — обычно подлежащее («Брат побил рекорд», «Коллега убил день»).
    const subjectPast = m && !/(?<![а-я])бы(?![а-я])/.test(s.slice(Math.max(0, m.index - 12), m.index + m[0].length + 4)) && !new RegExp(String.raw`^(?:причинить|слома|расправ|${HARM_VERB})`).test(m[0]) && /(?:ил|ал|ул|ел|ыл)(?:а|и|о)?(?![а-я])/.test(m[0].split(/\s+/).pop());
    if ((!m || subjectPast) && !named && !weaponPlan(s, t)) { if (PAST_NO_OBJ.test(s) && !level) level = 'concern'; continue; }
    // Признак намерения (решение, план, время) в том же предложении — в любом месте; или средство в рассказе.
    if (MARKER.test(s) || weapon) return 'urgent';
    level = 'concern';
  }
  return level;
}

