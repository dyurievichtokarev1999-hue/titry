// Действие против другого человека. Обязателен объект-человек (существительное или местоимение) рядом с глаголом:
// «напасть на след», «убить время», «избить рекорд», «ударить по мячу» — не угроза.
// Инфинитив, будущее и прошедшее (для «бы»: «так бы и убила его») — основами, с разговорными формами.
const HARM_VERB = String.raw`(?:причинить\s+(?:\S+\s+)?(?:вред|боль)|причинил(?:а|и|о)?\s+(?:\S+\s+)?(?:вред|боль)|удар(?:ить|ю|ил(?:а|и|о)?)|стукн(?:уть|у|ул(?:а|и|о)?)|вре(?:зать|жу|зал(?:а|и|о)?)|вмаж(?:у|ет)|вмазать|из?би(?:ть|л\S*)|изобью|поб(?:ить|ью|ил(?:а|и|о)?)|приб(?:ить|ью|ил(?:а|и|о)?)|уб(?:ить|ью|ил(?:а|и|о)?)|зарез(?:ать|ал(?:а|и|о)?)|зарежу|задуш(?:ить|у|ил(?:а|и|о)?)|придуш(?:ить|у|ил(?:а|и|о)?)|покалеч(?:ить|у|ил(?:а|и|о)?)|напа(?:сть|л(?:а|и|о)?)|нападу|отомст(?:ить|ил(?:а|и|о)?)|отомщу|пырн(?:уть|у|ул(?:а|и|о)?)|застрел(?:ить|ю|ил(?:а|и|о)?)|пристрел(?:ить|ю|ил(?:а|и|о)?)|отрав(?:ить|лю|ил(?:а|и|о)?)|расправ(?:иться|люсь|ился|илась)|уро(?:ю|ет)|урыть|пореш(?:у|ить|ил(?:а|и|о)?)|(?:слома(?:ю|ть|ем)|сломал\S*\s+(?:ему|ей|им|тебе))\s+(?:\S+\s+)?(?:руки|руку|ноги|ногу|шею|нос|челюсть)|подкарау(?:лю|лить)|порвал(?:а|и|о)?\s+бы|порв(?:ать|у)|двин(?:уть|у)|дал(?:а|и)?\s+бы|разобь(?:ю|ет)\s+(?:\S+\s+)?(?:голову|лицо|морду)|(?:положу|подсыплю|подмешаю|насыплю)\s+(?:\S+\s+)?(?:яд\S*|отрав\S*))`;
const PERSON = String.raw`(?:его|ее|их|ему|ей|им|тебя|тебе|вас|вам|него|нее|ним|ней|ними|мужик\S*|директор\S*|урод\S*|шеф\S*|тренер\S*|бабушк\S*|деда|деду|дедушк\S*|брат\S*|сестр\S*|мам\S*|мать|матери|пап\S*|отц\S*|отца|муж\S*|жен\S*|сосед\S*|коллег\S*|начальни\S*|отчим\S*|мачех\S*|свекр\S*|тещ\S*|бывш\S*|партнер\S*|друг\S*|подруг\S*|ребен\S*|сын\S*|доч\S*|учител\S*|одноклассни\S*|человек\S*|люд\S*|всех|парн\S*|девушк\S*)`;
// Глагол и объект в пределах трёх слов в любом порядке; «на» допускается («напасть на соседа»).
const HARM_PERSON = new RegExp(String.raw`(?<![а-я])причинить\s+${PERSON}\s+(?:вред|боль)|(?<![а-я])слома\S*\s+${PERSON}\s+(?:руки|руку|ноги|ногу|шею|нос|челюсть)|(?<![а-я])(?:расправ\S*|разберусь|поквитаюсь|сведу\s+счеты)\s+со?\s+${PERSON}(?![а-я])|(?<![а-я])${HARM_VERB}(?![а-я])(?:\s+(?!(?:с|со|вместе)\s)[^\s,;:—–]+){0,2}?\s+(?:на\s+)?(?<!(?:с|со)\s)${PERSON}(?![а-я])|(?<![а-я])${PERSON}(?![а-я,;:])(?:\s+[^\s,;:—–]+){0,2}?\s+${HARM_VERB}(?![а-я])|(?<![а-я])разобь\S*\s+${PERSON}\s+(?:голову|лицо|морду|нос|башку)|(?<![а-я])(?:положу|подсыплю|подмешаю|насыплю|подолью)\s+${PERSON}\s+(?:\S+\s+)?(?:яд\S*|отрав\S*)|(?<![а-я])(?:положу|подсыплю|подмешаю|насыплю|подолью)\s+(?:\S+\s+)?(?:яд\S*|отрав\S*)\s+${PERSON}(?![а-я])`);
const WANT = /(?:хочу|хочется|хотела|хотел|мечтаю|охота)/;
const MARKER = /(?<![а-я])(?:собираюсь|соберусь|решил\S*|решено|намерен\S*|планирую|план\S*|пойду|сегодня|завтра|ночью|вечером|сейчас|скоро|после\s+(?:работы|уроков|школы|пар)|в\s+(?:понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье)|на\s+выходных|в\s+выходные|через\s+(?:час|день|неделю))(?![а-я])/;
// Средство (оружие) рядом с намерением; «нож» — не «ножницы»; отрицание («нет ножа», «оружия у меня нет») не считается.
const WEAPON = /(?<!не\s)(?<!нет\s)(?:оружие|оружием|(?<![а-я])нож(?!ниц|ничк)\S*|пистолет\S*|ружье\S*|ружьем|бит(?:а|у|ой|о)(?![а-я]))(?![^.!?…;]{0,15}нет)/;

// Оружие и цель без глагола вреда: «Возьму нож и пойду к бывшему», «Нож в сумке. Сегодня он умрёт».
const WEAPON_PREP = /(?:возьму|взял\S*|наточил\S*|приготовил\S*|в\s+сумке|при\s+мне|за\s+поясом)/;
const DOOM = new RegExp(String.raw`(?:он|она|они)\s+(?:умрет|умрут|сдохнет|не\s+проснется)|(?<![а-я])${PERSON}\s+конец|(?:пойду|приду)\s+к\s+${PERSON}`);
function weaponPlan(sentence, whole) {
  return WEAPON.test(whole) && WEAPON_PREP.test(whole) && (DOOM.test(sentence) || DOOM.test(whole));
}
const clauses = (text) => String(text || '').split(/(?<=[.!?…;])\s+|\n+/).map((x) => x.trim()).filter(Boolean);
// Имя собственное (кириллица с заглавной, не первое слово предложения) рядом с глаголом: «убью Петю», «Серёгу урою».
const NAMED = new RegExp(String.raw`(?<![а-яА-ЯёЁ])${HARM_VERB}(?![а-я])\s+(?:\S+\s+)?[А-ЯЁ][а-яё]{2,}|[^.!?…;\s]\s+[А-ЯЁ][а-яё]{2,}\s+(?:\S+\s+)?${HARM_VERB}(?![а-я])`);
const INITIAL_NAMED = new RegExp(String.raw`^[А-ЯЁ][а-яё]{2,}[ую]\s+(?:\S+\s+){0,2}?(?!\S*(?:ил|ал|ул|ел|ыл)(?:а|и|о)?(?![а-я]))(?!\S*(?:ть|ться)(?![а-я]))${HARM_VERB}(?![а-я])`);
const namedHarm = (raw) => clauses(String(raw || '').replace(/ё/g, 'е').replace(/Ё/g, 'Е')).some((s) => NAMED.test(s.replace(/^[А-ЯЁ]/, (c) => c.toLowerCase()).replace(/^(\S+)/, (w) => w.toLowerCase())));

/** Уровень угрозы другому человеку по предложениям: 'urgent' | 'concern' | null. */
function harmToOthers(t, raw = '') {
  let level = null;
  const parts = clauses(t);
  const weapon = WEAPON.test(t);
  const rawParts = clauses(String(raw || '').replace(/ё/g, 'е').replace(/Ё/g, 'Е'));
  for (const [k, s] of parts.entries()) {
    const rp = rawParts[k];
    // Имя в начале предложения — только в винительном на -у/-ю и с личной формой глагола не в прошедшем («Серёгу урою», «Катю я сегодня придушу»; не «Пойду ударить…», не «Утку убила лиса»).
    const named = rp !== undefined && (NAMED.test(rp.replace(/^(\S+)/, (w) => w.toLowerCase())) || INITIAL_NAMED.test(rp));
    const m = HARM_PERSON.exec(s);
    // Человек перед глаголом в прошедшем времени — обычно подлежащее («Брат побил рекорд», «Коллега убил день»).
    const subjectPast = m && !/(?<![а-я])бы(?![а-я])/.test(s) && !new RegExp(String.raw`^(?:причинить|слома|расправ|${HARM_VERB})`).test(m[0]) && /(?:ил|ал|ул|ел|ыл)(?:а|и|о)?(?![а-я])/.test(m[0].split(/\s+/).pop());
    if ((!m || subjectPast) && !named && !weaponPlan(s, t)) continue;
    // Признак намерения (решение, план, время) в том же предложении — в любом месте; или средство в рассказе.
    if (MARKER.test(s) || weapon) return 'urgent';
    level = 'concern';
  }
  return level;
}

