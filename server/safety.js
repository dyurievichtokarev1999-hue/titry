// Нижняя граница безопасности. Это не диагностика и не надёжное обнаружение риска:
// фильтр ловит прямые формулировки, второй слой — флаг safety_flag от модели в draft.js.
// Если сработал любой слой, ролик не делается: вместо титров человек видит спокойный экран помощи.
// Обойти остановку нельзя (РЕШЕНИЕ Дмитрия от 7.11.2026, вариант А).
//
// Устойчивые выражения («умру от стыда», «готов убить себя за эту ошибку») не являются сигналом.
// Они вырезаются из текста ДО проверки, поэтому прямая формулировка рядом с ними всё равно остановит
// ролик: «умру от стыда, и вообще не хочу жить» → остановка. Список выражений намеренно узкий:
// всё, что может быть настоящим сигналом (тоска, одиночество, боль, усталость), в него не входит.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

const URGENT = [
  /не\s+хочу\s+(больше\s+)?жить/,
  /не\s+хочется\s+(больше\s+)?жить/,
  /хочу\s+умереть/,
  /хочется\s+умереть/,
  /(покончить|кончать|покончу)\s+с\s+собой/,
  /суицид/,
  /самоубий/,
  /уб(ить|ью)\s+себя/,
  /св(ести|еду)\s+сч[её]ты\s+с\s+жизнью/,
  /уйти\s+из\s+жизни/,
  /лучше\s+бы\s+меня\s+не\s+было/,
  /(всем|никому)\s+будет\s+лучше\s+без\s+меня/,
  /нет\s+смысла\s+жить/,
  /(режу|порезала?|резать)\s+себя/,
  /селфхарм|самоповрежд/,
  /наглотаться\s+таблеток/,
  /выпилиться/,
  /прыгнуть\s+с\s+(крыши|моста)/,
  /попрощаться\s+со\s+всеми\s+навсегда/,
  // Прямая опасность для самого человека (база: «опасность» — ролик не делается).
  /мне\s+угрожа/,
  /боюсь\s+за\s+свою\s+жизнь/,
  /меня\s+(?:бьет|бьют)(?!\s+(?:дрожь|озноб|током|ток|колотун|мандраж))/,
  /меня\s+(?:избил|избила|избили|избивает|избивают|ударил|ударила|ударили|душил|душила)/,

  // L01/L02 (решение владельца «в», 10.11): группы сигналов S редактора повествования — общие формулировки,
  // а не копии фикстур. Каждое правило проверено на всех гиперболах H (tests/local-rules.test.js).
  // Нежелание жить / исчезнуть / чтобы жизнь закончилась.
  /не\s+(?:хочу|хочется)\s+(?:больше\s+)?просыпаться/,
  /(?:не\s+собираюсь|не\s+хочу\s+больше)\s+жить/,
  /(?:исчезнуть|уйти)\s+навсегда/,
  /(?:хочу|хочется),?\s+чтобы\s+(?:моя\s+)?жизнь\s+(?:закончилась|кончилась|прекратилась)/,
  /желани\S*\s+(?:умереть|не\s+жить|исчезнуть)/,
  /не\s+вижу\s+смысла\s+(?:оставаться\s+в\s+живых|жить|просыпаться)/,
  // «Всем будет легче/лучше без меня / если меня не станет».
  /(?:легче|лучше)[^.!?…]{0,40}(?:без\s+меня|меня\s+не\s+станет)/,
  /(?:без\s+меня|меня\s+не\s+станет)[^.!?…]{0,40}(?:легче|лучше)/,
  // Прощание навсегда.
  /прощальн\S*\s+(?:сообщени|письм|записк|слов)/,
  // Самоповреждение: «навредить себе», «причинить себе вред/боль», «не удержаться», «страшно за себя».
  /(?:навредить|навред\S*)\s+себе|себе\s+навредить/,
  /причинить\s+себе\s+(?:вред|боль)/,
  /не\s+смогу\s+удержаться|смогу\s+ли\s+удержаться|не\s+уверен\S*,?\s+что\s+смогу\s+удержаться/,
  /страшно\s+за\s+себя/,
  /не\s+могу\s+обещать,?\s+что\s+буду\s+в\s+безопасности/,
  // Опасность от других: угрозы, побои, удержание, контроль связи.
  /угрожа\S*\s+мне|мне\s+угрожа/,
  /небезопасно\s+(?:дома|мне|сейчас)/,
  /меня\s+(?:сейчас|снова|опять|постоянно)\s+(?:бьет|бьют)/,
  /(?:обещал\S*|грозит\S*|грозил\S*)\s+(?:меня\s+)?(?:избить|убить|расправиться)/,
  /расправиться\s+со\s+мной/,
  /боюсь\s+за\s+(?:свою\s+)?жизнь/,
  /не\s+выпуска\S*\s+меня/,
  /телефон\s+(?:велят|велел\S*|заставля\S*|требу\S*)\s+(?:отключить|выключить|отдать)/,
];

// Гнев на других — частая гипербола («убью его, если опоздает»): ролик собирается, рядом — контакты помощи.
const CONCERN = [
  /(убью|прибью|убить\s+готова?)\s+(его|е[её]|их|тебя)/,
];

function norm(text) {
  return String(text || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
}

// Причины в «умереть от …», которые в русском — гипербола, а не мысль о смерти.
// Нет и не должно быть: тоски, одиночества, боли, усталости, горя, безысходности.
const HYPERBOLE_CAUSES = 'стыда|смеха|смеху|скуки|любопытства|зависти|жары|холода|голода|счастья|радости|восторга|умиления|нетерпения|неловкости|кринжа|испанского стыда|ревности';
const DIE = '(?:умереть|помереть|сдохнуть|умру|помру|сдохну|умираю|помираю|подыхаю)';

const IDIOMS = [
  // «хочу умереть от стыда», «умру со смеху», «можно сдохнуть от скуки»
  new RegExp(`(?:(?:хочу|хочется|готова?|можно|щас|сейчас)\\s+)?(?:просто\\s+|прямо\\s+|аж\\s+)?${DIE}\\s+(?:от|со?)\\s+(?:${HYPERBOLE_CAUSES})`, 'g'),
  // «готов убить себя за эту ошибку», «убить себя готова за то, что забыла»
  /готова?\s+убить\s+себя\s+за/g,
  /убить\s+себя\s+готова?\s+за/g,
  // «не хочу жить в этой квартире / в этом городе / с родителями» — про жильё и соседство, не про жизнь.
  // «в этом мире», «на этом свете», «с этой болью» сюда не попадают и останавливают ролик.
  /не\s+(?:хочу|хочется)\s+(?:больше\s+)?жить\s+(?:в|во|на|у|рядом\s+с|возле|около)\s+(?:эт\S*\s+|сво\S*\s+|тако\S*\s+|одн\S*\s+)?(?:квартир|доме|дому|общаг|общежити|городе|москве|питере|районе|деревне|стране|комнате|съемн|центре|пригороде|подвале|офисе|соседств)\S*/g,
  /не\s+(?:хочу|хочется)\s+(?:больше\s+)?жить\s+(?:с|со|вместе\s+с)\s+(?:родител|мам|пап|сосед|свекр|тещ|бывш|парн|девушк|муж|жен|сестр|брат|ними(?=[\s.,!?…]|$)|ним(?=[\s.,!?…]|$)|ней(?=[\s.,!?…]|$))\S*/g,
];

/** Убрать из текста устойчивые выражения. Экспортируется для тестов. */
export function stripIdioms(text) {
  let t = norm(text);
  for (const re of IDIOMS) t = t.replace(re, ' · ');
  return t;
}

/**
 * Оценка рассказа. level: 'none' | 'concern' | 'urgent'.
 * modelFlag — необязательный флаг от модели черновика (второй слой).
 */
export function assessRisk(text, modelFlag = false) {
  const t = stripIdioms(text);
  const urgent = URGENT.filter((re) => re.test(t)).map(String);
  if (urgent.length || modelFlag) return { level: 'urgent', matches: urgent, byModel: !!modelFlag && !urgent.length };
  const concern = CONCERN.filter((re) => re.test(t)).map(String);
  if (concern.length) return { level: 'concern', matches: concern, byModel: false };
  return { level: 'none', matches: [], byModel: false };
}

/**
 * Проверка перед рендером: рассказ и все тексты эпизода вместе.
 * Правки после черновика тоже проверяются — опасная строка не попадёт в ролик.
 */
export function assessEpisodeRisk(story, ep) {
  const parts = [story];
  if (ep) {
    parts.push(ep.title, ep.genre, ep.lead);
    for (const r of ep.rows || []) parts.push(r.role, r.value);
    if (ep.post) parts.push(ep.post.text);
  }
  return assessRisk(parts.filter(Boolean).join('\n'));
}

export function loadHelp(file = path.join(here, '..', 'config', 'help.json')) {
  const cfg = JSON.parse(fs.readFileSync(file, 'utf8'));
  const contacts = [cfg.emergency, ...(cfg.contacts || [])].filter((c) => c && c.verified && c.phone);
  return { region: cfg.region, contacts };
}

/** Текст экрана помощи. Без обещаний «мы всегда заметим» и без давления. */
export function helpMessage(level, help = loadHelp()) {
  const list = help.contacts.map((c) => `• ${c.label}: ${c.phone}${c.hours ? ` (${c.hours})` : ''}`).join('\n');
  if (level === 'urgent') {
    return [
      'Сейчас важнее не титры, а ты.',
      'В рассказе есть слова о том, что жить не хочется или есть опасность. Я не буду делать из этого ролик.',
      'Если есть риск прямо сейчас, позвони по одному из номеров или попроси кого-то рядом побыть с тобой:',
      list,
      'Когда захочется, можно прислать новый рассказ о дне.',
    ].join('\n\n');
  }
  return [
    'Похоже, в этом дне было что-то опасное или очень тяжёлое.',
    'Если тебе или кому-то рядом угрожает опасность, лучше обратиться за живой помощью:',
    list,
  ].join('\n\n');
}
