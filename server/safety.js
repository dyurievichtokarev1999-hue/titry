function norm(text) {
  // Слитное «не» с глаголами желания — частая опечатка («нехочу жить»): разделяется до проверки правил.
  return String(text || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ')
    .replace(/(?<![а-я])не(хочу|хочется|могу|вижу|собираюсь)(?![а-я])/g, 'не $1');
}

