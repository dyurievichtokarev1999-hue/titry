// Проверка выпуска для реальных данных (TITRY_RELEASE_REAL_DATA=1): тексты, которые увидит участник, — окончательные.
// Решение Claude 19.11: ни одного поля в квадратных скобках — ни незаполненного («[контакт оператора]»), ни условного
// («[если включено]»); условных кусков в круглых скобках («(если включено)») тоже. Используется при старте бота
// (prepareBot) и в tests/release-guard.test.js.

// Маркеры незаполненного в любом выпускаемом файле; регистр и «е/ё» не важны.
export const MARKER_RE = /\[\s*(?:жд[её]т решения|на согласование с юристом|срок не утвержд[её]н)[^\]\n]*\]?/giu;

// Тексты проверяются как текст, а не как исходник. Находка — любое поле в квадратных скобках (с любым началом,
// содержимым и переносами строк), любая одиночная скобка «[» или «]» (бот отправляет текст без разметки — участник
// увидит скобки как есть, и в ссылке тоже) и условный кусок в круглых скобках.
export const bracketFields = (text) => [...String(text).matchAll(/\[[^[\]]*\]|[[\]]|\*?\((?=[^)]*(?:если\s+включ|только\s+(?:для\s+теста|если)))[^)]*\)\*?/giu)].map(([m]) => m);

// Ключи текстов с находками, например «CONSENT_TEXT.pd». Содержимое находок не возвращается: в журнал — только ключи.
export function unfinishedTexts(groups) {
  const keys = [];
  for (const [group, texts] of Object.entries(groups)) {
    for (const [key, v] of Object.entries(texts)) {
      if (bracketFields(typeof v === 'function' ? v() : v).length) keys.push(`${group}.${key}`);
    }
  }
  return keys;
}
