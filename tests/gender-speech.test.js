// Род только из собственных слов рассказчика: чужая речь не считается.
// Контрольный набор — из сообщений координатора и редактора GPT от 7.11.2026. Все тексты вымышленные.
import test from 'node:test';
import assert from 'node:assert/strict';
import { detectGender } from '../engine/episode.js';

test('чужая реплика не определяет род рассказчика', () => {
  // quoted-other из набора 10 историй
  assert.equal(detectGender('Подруга написала: «Я устала и хочу тишины». Встреча за чаем прошла молча. Потом полив цветов дома. Мой день был спокойным.'), null);
  assert.equal(detectGender('Я устала. Подруга написала: „Я в порядке“'), 'f');
  assert.equal(detectGender('Подруга написала: „Я устала“. Я полил цветы.'), 'm');
  assert.equal(detectGender('Я устал. Я устала.'), null);
  assert.equal(detectGender('Подруга написала: «Я устала. Я полил цветы.'), null, 'незакрытая кавычка — нет уверенной догадки');
  assert.equal(detectGender('Брат сказал: я сегодня опоздал. Мы поужинали.'), null, 'реплика без кавычек после «сказал:»');
  assert.equal(detectGender('Брат сказал: я опоздал. Я весь вечер читала.'), 'f', 'собственные слова после реплики сохраняются');
});

test('собственные слова определяют род как раньше', () => {
  assert.equal(detectGender('Сегодня разбирала мамин шкаф. Мамы нет уже три месяца. Я плакала на кухне.'), 'f');
  assert.equal(detectGender('Я сидел у окна и смотрел на дождь.'), 'm');
  assert.equal(detectGender('Меня зовут Саша. Утром кофе на балконе.'), null, 'имя не определяет род');
  // own-quote-is-own: собственная заметка в кавычках — допустимы f или null, но не m
  assert.notEqual(detectGender('Сегодня у меня только заметка в телефоне: «Я устала». Это мои слова о себе сейчас.'), 'm');
});
