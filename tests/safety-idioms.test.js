// Фильтр безопасности: устойчивые выражения против настоящих сигналов.
// РЕШЕНИЕ Дмитрия от 7.11.2026: вариант А (обхода нет) + фильтр должен отличать гиперболы от настоящих мыслей.
// Все фразы вымышленные. Списки — нижняя граница: набор редактора повествования добавится сюда же.
import test from 'node:test';
import assert from 'node:assert/strict';
import { assessRisk } from '../server/safety.js';

// Обязаны останавливать ролик — всегда, в любом окружении.
const MUST_STOP = [
  'Хочу умереть.',
  'Иногда хочется умереть, так устала от всего.',
  'Хочется умереть от тоски.',
  'Хочу умереть от одиночества.',
  'Не хочу больше жить.',
  'Не хочу жить в этом мире.',
  'Не хочу жить на этом свете.',
  'Не хочу жить с этой болью.',
  'Не хочу жить так.',
  'Думаю покончить с собой.',
  'Мысли о самоубийстве не отпускают.',
  'Хочется убить себя.',
  'Лучше бы меня не было.',
  'Всем будет лучше без меня.',
  'Опять режу себя.',
  'Хочу наглотаться таблеток.',
  'Нет смысла жить.',
  // Гипербола рядом с прямой формулировкой не прикрывает её
  'Умру от стыда, и вообще не хочу жить.',
  'Готов убить себя за эту ошибку. А если честно, не хочу больше жить.',
  'Не хочу жить в этой квартире. И вообще не хочу жить.',
  'Не хочу жить с ним. Не хочу больше жить.',
];

// Не должны останавливать: обычная речь о неловком, смешном или бытовом дне.
const MUST_PASS = [
  'Хочу умереть от стыда, так опозорилась на встрече.',
  'Чуть не умер со смеху, когда кот уронил ёлку.',
  'Можно сдохнуть от скуки на этих планёрках.',
  'Умру от любопытства, если не узнаю, чем кончится сериал.',
  'Сейчас умру от умиления.',
  'Готов убить себя за эту ошибку в отчёте.',
  'Убить себя готова за то, что забыла про день рождения мамы.',
  'Не хочу больше жить в этой квартире, соседи шумят.',
  'Не хочу жить в Москве, хочу к морю.',
  'Не хочу жить с родителями, пора съезжать.',
  'Не хочу жить с ним, мы постоянно ругаемся.',
  'Сегодня просто устал и хочу спать.',
];

test('прямые формулировки останавливают ролик всегда', () => {
  for (const t of MUST_STOP) assert.equal(assessRisk(t).level, 'urgent', t);
});

test('устойчивые выражения не останавливают ролик', () => {
  for (const t of MUST_PASS) assert.notEqual(assessRisk(t).level, 'urgent', t);
});

test('флаг модели по-прежнему останавливает, даже если в тексте одни гиперболы', () => {
  assert.equal(assessRisk('Хочу умереть от стыда.', true).level, 'urgent');
});
