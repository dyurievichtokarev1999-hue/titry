test('Титры: «мать/матери/матерь» и «отец/отца» — один человек', () => {
  const E = (st, over) => threatErrors(st, { title: 'Чай', genre: 'драма', lead: 'я', rows: [], post: { text: '', source: '' }, ...over }).map((x) => x.path);
  const m = 'Утром гуляла с собакой. Завтра отравлю мать крысиным ядом. Вечером пила чай.';
  for (const title of ['Матери', 'Матерь']) assert.deepEqual(E(m, { title }), ['title'], title);
  assert.deepEqual(E(m, { lead: 'матери' }), ['lead']);
  const f = 'Решено: сегодня ночью зарежу отца на кухне. Утром пила кофе.';
  assert.deepEqual(E(f, { title: 'Отец' }), ['title']);
  assert.deepEqual(E(f, { title: 'Утренний кофе' }), []);
});

