test('Нет экспоненциального перебора: длинные серии знаков после человека проверяются быстро', () => {
  for (const t of ['Мама' + '.'.repeat(60), 'Сегодня была у мамы' + ')'.repeat(60), 'Сосед2024' + '_'.repeat(60), 'Брата' + '-,.'.repeat(40) + ' завтра убью', ('Мама)))) ').repeat(600)]) {
    const start = performance.now();
    lv(t);
    threatErrors(t, { title: 'x', genre: 'y', lead: 'z', rows: [], post: { text: '', source: '' } });
    assert.ok(performance.now() - start < 500, t.slice(0, 20));
  }
});

