  for (const s of ['Начальник довёл, так бы и придушила.', 'Муж пришёл пьяный, я бы убила.', 'Брат, клянусь, я бы убил.', 'Брат достал, задушу всем телом.']) assert.notEqual(lv(s), 'none', s);
  for (const s of ['Сын попросил, в выходные двину на дачу.', 'Брат с утра на работе, я вечером ударю по газам.', 'Мама купила гвозди, завтра прибью картину.']) assert.equal(lv(s), 'none', s);
