// Бытовые фразы критика продукта (ИДЕЯ 14.11) — не останавливают ролик: локальный фильтр none.
// Пп. 8 («Мне не жить без кофе.») и 9 («Утоплюсь в работе.») сейчас дают urgent и ждут решения Claude — здесь их нет.
// Парный контроль: та же фраза и отдельный явный сигнал в следующем предложении — остановка сохраняется.
import test from 'node:test';
import assert from 'node:assert/strict';
import { assessRisk } from '../server/safety.js';

const PHRASES = [
  'В январе я впервые сама починила кофемолку. Без кофе мне не жить.',
  'Утром поезд задержался, зато в буфете был кофе. Убить готова за кофе!',
  'В августе после концерта очередь была только в одну палатку. Отравлюсь шавермой…',
  'На даче сломалась турка, и я варила кофе в ковшике. Без кофе мне не жить!',
  'На ночной пересадке мы нашли открытый киоск. Убить готова за кофе.',
  'В ноябре у метро открыли новый киоск. Отравлюсь шавермой.',
  'Я выложила на подоконнике весь первый урожай помидоров. Умру от стыда: два уже успели лопнуть.',
  'На новогодней вечеринке я вышла на сцену в тапочках. Чуть не умерла со смеху.',
];

test('бытовые фразы критика продукта — без остановки', () => {
  for (const t of PHRASES) assert.equal(assessRisk(t).level, 'none', t);
});

test('та же бытовая фраза + явный сигнал в следующем предложении — остановка сохраняется', () => {
  for (const t of PHRASES) assert.equal(assessRisk(`${t} Я не хочу больше жить.`).level, 'urgent', t);
});
